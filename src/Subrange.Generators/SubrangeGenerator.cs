using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Subranges.Generators;

/// <summary>
/// Completes every valid <c>[Subrange&lt;TValue&gt;]</c> type with its private constructor,
/// <c>Value</c>, <c>Min</c>/<c>Max</c>, <c>Parse</c>/<c>TryParse</c> for numbers and text,
/// <c>ToString</c>, JSON converter and type converter. Types breaking a rule in
/// <see cref="SubrangeRules"/> are skipped and reported by <see cref="SubrangeAnalyzer"/>.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SubrangeGenerator : IIncrementalGenerator
{
    private sealed record Model(
        string? Namespace,
        string Name,
        string ValueType,
        string Min,
        string Max
    );

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var models = context.SyntaxProvider.ForAttributeWithMetadataName(
            SubrangeRules.MetadataName,
            static (_, _) => true,
            static (attributeContext, _) =>
            {
                var type = (INamedTypeSymbol)attributeContext.TargetSymbol;
                var attribute = attributeContext.Attributes[0];

                return
                    !SubrangeRules.Violations(type, attribute).Any()
                    && SubrangeRules.Bounds(attribute)
                        is { MinText: { } min, MaxText: { } max } bounds
                    ? new Model(
                        type.ContainingNamespace.IsGlobalNamespace
                            ? null
                            : type.ContainingNamespace.ToDisplayString(),
                        type.Name,
                        bounds.ValueType,
                        min,
                        max
                    )
                    : null;
            }
        );

        context.RegisterSourceOutput(
            models,
            static (sourceContext, model) =>
            {
                if (model is null)
                    return;

                var name = model.Name;
                var value = model.ValueType;
                var min = SymbolDisplay.FormatLiteral(model.Min, quote: true);
                var max = SymbolDisplay.FormatLiteral(model.Max, quote: true);
                var range = $"from {model.Min} to {model.Max} inclusive";
                var namespaceLine = model.Namespace is null ? "" : $"namespace {model.Namespace};";

                sourceContext.AddSource(
                    $"{model.Namespace}.{name}.g.cs".TrimStart('.'),
                    $$"""
                    // <auto-generated/>
                    #nullable enable

                    {{namespaceLine}}

                    /// <remarks>Holds a <see cref="{{value}}"/> {{range}}.</remarks>
                    [global::System.Text.Json.Serialization.JsonConverter(typeof({{name}}.SubrangeJsonConverter))]
                    [global::System.ComponentModel.TypeConverter(typeof({{name}}.SubrangeTypeConverter))]
                    partial record {{name}} : global::System.IParsable<{{name}}>
                    {
                        // Parsed rather than written as literals, so the same text works for every number type.
                        /// <summary>The smallest value allowed: {{model.Min}}.</summary>
                        public static {{value}} Min { get; } = ParseBound<{{value}}>({{min}});

                        /// <summary>The largest value allowed: {{model.Max}}.</summary>
                        public static {{value}} Max { get; } = ParseBound<{{value}}>({{max}});

                        /// <summary>The error message for a value outside {{model.Min}} to {{model.Max}}.</summary>
                        public static string OutOfRangeMessage =>
                            global::System.FormattableString.Invariant($"{{name}} must be between {Min} and {Max}.");

                        /// <summary>The value, always {{range}}.</summary>
                        public {{value}} Value { get; }

                        private {{name}}({{value}} value)
                        {
                            Value = value;
                        }

                        // The bounds are finite, so NaN and infinities fail these comparisons.
                        /// <summary>Whether <paramref name="value"/> is {{range}}.</summary>
                        public static bool IsInRange({{value}} value) =>
                            value >= Min && value <= Max;

                        /// <summary>Accepts <paramref name="value"/> if it is {{range}}.</summary>
                        public static bool TryParse(
                            {{value}} value,
                            [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out {{name}}? result
                        )
                        {
                            result = IsInRange(value) ? new {{name}}(value) : null;
                            return result is not null;
                        }

                        /// <summary>Accepts <paramref name="value"/> if it is {{range}}.</summary>
                        /// <exception cref="global::System.ArgumentOutOfRangeException"><paramref name="value"/> is outside <see cref="Min"/> and <see cref="Max"/>.</exception>
                        public static {{name}} Parse({{value}} value) =>
                            TryParse(value, out var result)
                                ? result
                                : throw new global::System.ArgumentOutOfRangeException(nameof(value), value, OutOfRangeMessage);

                        /// <summary>Accepts <paramref name="value"/> if it is exactly a <see cref="{{value}}"/> {{range}}.</summary>
                        /// <exception cref="global::System.NotSupportedException"><typeparamref name="TNumber"/> can't be converted to or from <see cref="Value"/>'s type.</exception>
                        public static bool TryParse<TNumber>(
                            TNumber value,
                            [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out {{name}}? result
                        )
                            where TNumber : global::System.Numerics.INumberBase<TNumber>
                        {
                            result = null;
                            return TryConvertExactly<TNumber, {{value}}>(value, out var converted)
                                && TryParse(converted, out result);
                        }

                        /// <summary>Accepts <paramref name="value"/> if it is exactly a <see cref="{{value}}"/> {{range}}.</summary>
                        /// <exception cref="global::System.ArgumentOutOfRangeException"><paramref name="value"/> is outside <see cref="Min"/> and <see cref="Max"/>, or isn't exactly a value of <see cref="Value"/>'s type.</exception>
                        /// <exception cref="global::System.NotSupportedException"><typeparamref name="TNumber"/> can't be converted to or from <see cref="Value"/>'s type.</exception>
                        public static {{name}} Parse<TNumber>(TNumber value)
                            where TNumber : global::System.Numerics.INumberBase<TNumber> =>
                            TryParse(value, out var result)
                                ? result
                                : throw new global::System.ArgumentOutOfRangeException(nameof(value), value, OutOfRangeMessage);

                        /// <summary>Accepts <paramref name="s"/> if it is a number {{range}}.</summary>
                        public static bool TryParse(
                            [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] string? s,
                            global::System.IFormatProvider? provider,
                            [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out {{name}}? result
                        )
                        {
                            result = null;
                            return TryParseText<{{value}}>(s, provider, out var value)
                                && TryParse(value, out result);
                        }

                        /// <summary>Accepts <paramref name="s"/> if it is a number {{range}}.</summary>
                        /// <exception cref="global::System.FormatException"><paramref name="s"/> is not a number, or is outside <see cref="Min"/> and <see cref="Max"/>.</exception>
                        public static {{name}} Parse(string s, global::System.IFormatProvider? provider)
                        {
                            if (!TryParseText<{{value}}>(s, provider, out var value))
                                throw new global::System.FormatException($"'{s}' is not a number.");

                            return TryParse(value, out var result)
                                ? result
                                : throw new global::System.FormatException(OutOfRangeMessage);
                        }

                        /// <summary>The value as invariant-culture text.</summary>
                        public override string ToString() =>
                            Value.ToString(null, global::System.Globalization.CultureInfo.InvariantCulture);

                        // Generic so that number types implementing these members explicitly work too.
                        private static TNumber ParseBound<TNumber>(string text)
                            where TNumber : global::System.Numerics.INumberBase<TNumber> =>
                            TNumber.Parse(text, global::System.Globalization.NumberStyles.Float, global::System.Globalization.CultureInfo.InvariantCulture);

                        // Saturating and converting back rejects values that are out of range, fractional or NaN,
                        // where truncating would wrap them and saturating alone would clamp them. A source too
                        // coarse to hold the target's extreme can still saturate onto it and convert back to
                        // itself, such as 2147483648f onto int.MaxValue, so both are also compared as doubles.
                        // A double holds every in-range integer exactly, since integer bounds are at most 2^53.
                        private static bool TryConvertExactly<TNumber, TTarget>(TNumber value, [global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] out TTarget converted)
                            where TNumber : global::System.Numerics.INumberBase<TNumber>
                            where TTarget : global::System.Numerics.INumberBase<TTarget>
                        {
                            converted = TTarget.CreateSaturating(value);
                            return TNumber.CreateSaturating(converted) == value
                                && double.CreateSaturating(value) == double.CreateSaturating(converted);
                        }

                        private static bool TryParseText<TNumber>(string? s, global::System.IFormatProvider? provider, [global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] out TNumber value)
                            where TNumber : global::System.Numerics.INumberBase<TNumber> =>
                            TNumber.TryParse(s, provider ?? global::System.Globalization.CultureInfo.InvariantCulture, out value);

                        private static bool TryParseNumber<TNumber>(global::System.ReadOnlySpan<byte> utf8, [global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] out TNumber value)
                            where TNumber : global::System.Numerics.INumberBase<TNumber> =>
                            TNumber.TryParse(utf8, global::System.Globalization.NumberStyles.Float, global::System.Globalization.CultureInfo.InvariantCulture, out value);

                        private static bool TryParseNumber<TNumber>(string? text, [global::System.Diagnostics.CodeAnalysis.MaybeNullWhen(false)] out TNumber value)
                            where TNumber : global::System.Numerics.INumberBase<TNumber> =>
                            TNumber.TryParse(text, global::System.Globalization.NumberStyles.Float, global::System.Globalization.CultureInfo.InvariantCulture, out value);

                        // Utf8JsonWriter has no overload for every number type, so the number is formatted
                        // and written as raw JSON. 64 bytes hold any built-in number in its shortest form.
                        private static void WriteNumber<TNumber>(global::System.Text.Json.Utf8JsonWriter writer, TNumber value)
                            where TNumber : global::System.IUtf8SpanFormattable, global::System.IFormattable
                        {
                            global::System.Span<byte> utf8 = stackalloc byte[64];
                            if (value.TryFormat(utf8, out var written, default, global::System.Globalization.CultureInfo.InvariantCulture))
                                writer.WriteRawValue(utf8[..written], skipInputValidation: true);
                            else
                                writer.WriteRawValue(value.ToString(null, global::System.Globalization.CultureInfo.InvariantCulture));
                        }

                        // Only a JSON number is accepted, not a numeric string. JsonException rather than
                        // ArgumentException: ASP.NET Core turns it into a 400, anything else into a 500.
                        private sealed class SubrangeJsonConverter : global::System.Text.Json.Serialization.JsonConverter<{{name}}>
                        {
                            public override {{name}} Read(
                                ref global::System.Text.Json.Utf8JsonReader reader,
                                global::System.Type typeToConvert,
                                global::System.Text.Json.JsonSerializerOptions options
                            )
                            {
                                // Parsed from the raw bytes rather than by a nested JsonSerializer call, which would lose the property path.
                                global::System.ReadOnlySpan<byte> text = reader.HasValueSequence
                                    ? global::System.Buffers.BuffersExtensions.ToArray(reader.ValueSequence)
                                    : reader.ValueSpan;

                                return reader.TokenType == global::System.Text.Json.JsonTokenType.Number
                                    && TryParseNumber<{{value}}>(text, out var value)
                                    && TryParse(value, out var result)
                                    ? result
                                    : throw new global::System.Text.Json.JsonException(OutOfRangeMessage);
                            }

                            public override void Write(
                                global::System.Text.Json.Utf8JsonWriter writer,
                                {{name}} value,
                                global::System.Text.Json.JsonSerializerOptions options
                            ) => WriteNumber(writer, value.Value);

                            // A dictionary key is always a JSON string, so it's read as the text of a number.
                            public override {{name}} ReadAsPropertyName(
                                ref global::System.Text.Json.Utf8JsonReader reader,
                                global::System.Type typeToConvert,
                                global::System.Text.Json.JsonSerializerOptions options
                            ) =>
                                TryParseNumber<{{value}}>(reader.GetString(), out var value)
                                && TryParse(value, out var result)
                                    ? result
                                    : throw new global::System.Text.Json.JsonException(OutOfRangeMessage);

                            public override void WriteAsPropertyName(
                                global::System.Text.Json.Utf8JsonWriter writer,
                                {{name}} value,
                                global::System.Text.Json.JsonSerializerOptions options
                            ) => writer.WritePropertyName(value.ToString());
                        }

                        // Microsoft.Extensions.Configuration binds text only through a TypeConverter, not IParsable.
                        // Without one it binds the type as an object with no properties and silently yields null.
                        private sealed class SubrangeTypeConverter : global::System.ComponentModel.TypeConverter
                        {
                            public override bool CanConvertFrom(global::System.ComponentModel.ITypeDescriptorContext? context, global::System.Type sourceType) =>
                                sourceType == typeof(string) || base.CanConvertFrom(context, sourceType);

                            /// <exception cref="global::System.FormatException"><paramref name="value"/> is not a number, or is outside <see cref="Min"/> and <see cref="Max"/>.</exception>
                            /// <exception cref="global::System.NotSupportedException"><paramref name="value"/> is not a string.</exception>
                            public override object? ConvertFrom(
                                global::System.ComponentModel.ITypeDescriptorContext? context,
                                global::System.Globalization.CultureInfo? culture,
                                object value
                            ) =>
                                value is string text
                                    ? Parse(text, culture)
                                    : base.ConvertFrom(context, culture, value);
                        }
                    }

                    """
                );
            }
        );
    }
}
